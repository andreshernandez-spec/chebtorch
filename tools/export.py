"""Write chebtorch's generated table modules and fixtures from chebax.

    python tools/export.py                 # every family's _<family>_data.py
    python tools/export.py --fixtures      # also the mpmath fixtures (~1 min)

This is the only code in chebtorch that imports chebax (and so jax) or mpmath,
and only inside the functions below: tests import `data_sha256` from here
without either. For each family it writes src/chebtorch/_<family>_data.py, a
module of literals: PROVENANCE (chebax describe and commit, the table module,
its generator hash, mpmath version and dps from its META, the sha256 of the
data), the scalar constants, SHAPES and DATA, float64 values as repr, which
round-trips exactly. With --fixtures it also computes the mpmath references in
tests/fixtures/.
"""

import argparse
import hashlib
import importlib
import json
import math
import pathlib
import random
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "chebtorch"

# family -> (chebax table module, scalars to carry)
FAMILIES = {
    "tweedie": ("chebax._src.recipes.tweedie_table",
                ("P_LO", "P_HI", "RHO_MIN", "RHO_MAX", "A1", "ZA", "S1", "N_TERMS")),
}

HEADER = '''# Copyright (c) 2026, Andres Hernandez
# SPDX-License-Identifier: BSD-3-Clause (https://github.com/andreshernandez-spec/chebtorch)
"""Tables for chebtorch.{family}, generated by tools/export.py from chebax; do
not edit. PROVENANCE names the chebax commit, table module and generator;
tests/test_contract.py checks DATA against its sha256.
"""
'''


def data_sha256(shapes, data):
    """sha256 of the generated data, in the form the data module holds it."""
    h = hashlib.sha256()
    for name in sorted(data):
        h.update(f"{name} {tuple(shapes[name])}\n".encode())
        h.update("\n".join(repr(float(v)) for v in data[name]).encode())
    return h.hexdigest()


def chebax_provenance(table_mod):
    import chebax
    repo = pathlib.Path(chebax.__file__).resolve().parents[2]
    rel = pathlib.Path(table_mod.__file__).resolve().relative_to(repo)

    def git(*args):
        return subprocess.run(["git", "-C", str(repo), *args], capture_output=True,
                              text=True, check=True).stdout.strip()

    # the last commit that changed the table, so later chebax commits that
    # leave it alone do not move the provenance
    commit = git("log", "-1", "--format=%H", "--", str(rel))
    dirty = git("status", "--porcelain", "--", str(rel))
    meta = table_mod.META
    return {
        # describe, not the package version: a checkout past a tag still
        # reports the tag's version, whose release may predate the table
        "chebax": git("describe", "--tags", "--always", commit),
        "chebax_commit": commit + ("-dirty" if dirty else ""),
        "table_module": table_mod.__name__,
        "generator_sha256": meta["generator_sha256"],
        "mpmath": meta["mpmath"],
        "dps": meta["dps"],
    }


def data_module(family):
    import numpy as np
    mod_name, scalar_names = FAMILIES[family]
    tm = importlib.import_module(mod_name)
    arrays = {k: np.asarray(v, dtype=np.float64) for k, v in vars(tm).items()
              if isinstance(v, np.ndarray)}
    shapes = {k: a.shape for k, a in arrays.items()}
    data = {k: [float(v) for v in a.ravel()] for k, a in arrays.items()}
    prov = dict(chebax_provenance(tm), data_sha256=data_sha256(shapes, data))
    lines = [HEADER.format(family=family), "PROVENANCE = {"]
    lines += [f"    {k!r}: {v!r}," for k, v in prov.items()]
    lines.append("}")
    lines += [f"{k} = {getattr(tm, k)!r}" for k in scalar_names]
    lines.append("SHAPES = {" + ", ".join(f"{k!r}: {shapes[k]!r}" for k in sorted(shapes)) + "}")
    lines.append("DATA = {")
    for k in sorted(data):
        lines.append(f"    {k!r}: (")
        vals = [repr(v) for v in data[k]]
        lines += ["        " + ", ".join(vals[i:i + 4]) + "," for i in range(0, len(vals), 4)]
        lines.append("    ),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def export_family(family):
    path = SRC / f"_{family}_data.py"
    path.write_text(data_module(family))
    print(f"wrote {path.relative_to(ROOT)}")


def tweedie_fixtures():
    sys.path.insert(0, str(ROOT / "tools"))
    import mpmath as mp
    import references as ref
    tt = importlib.import_module(FAMILIES["tweedie"][0])
    rhos = [1 / 19, 0.07, 0.111, 0.25, 0.5, 1.0, 2.0, 4.0, 9.0, 14.0, 19.0]
    wright = []
    for rho in rhos:
        z1 = tt.ZA + tt.S1 * (1 + rho) ** 2
        for big_z in (1e-6, 0.01, 0.5, 3.0, 0.9 * z1, z1 * (1 - 1e-9), z1 * (1 + 1e-9),
                      1.5 * z1, 10 * z1, 1e3, 1e4, 1e5):
            z = float(ref.z_of(rho, big_z))
            lw = ref.log_phi(rho, 0, z)
            wright.append({"rho": rho, "z": z, "value": float(lw),
                           "dz": float(mp.exp(ref.log_phi(rho, rho, z) - lw)),
                           "drho": float(ref.dlog_phi0_drho(rho, z))})
    cases = [(p, mu, phi, y)
             for p in (1.05, 1.08, 1.2, 1.5, 1.8, 1.95)
             for mu, phi in ((1.0, 1.0), (50.0, 0.05), (0.2, 3.0), (3.0, 0.3), (8.0, 1.7))
             for y in (0.0, 1e-6, 0.05, 0.9, 3.0, 20.0, 150.0)
             if y == 0 or y ** (2 - p) / (phi * (2 - p) * (p - 1)) <= 1e5]
    graded = {c for c in cases if c[3] in (0.0, 0.05, 3.0, 150.0) and c[1] in (1.0, 50.0, 3.0)}
    # just below the split at small p, where the density and its gradients
    # are worst: lgamma(rho n) reaches ~4000 there (found by comparing with
    # chebax on random inputs; the grid above misses it)
    for p in (1.05, 1.06, 1.08, 1.15):
        rho = (2 - p) / (p - 1)
        z1 = tt.ZA + tt.S1 * (1 + rho) ** 2
        for phi in (0.01, 0.07, 0.3, 1.5):
            for frac in (0.5, 0.8, 0.9, 0.97):
                y = (frac * z1 * phi * (2 - p) * (p - 1)) ** (1 / (2 - p))
                graded |= {(p, y * r, phi, y) for r in (0.6, 1.2, 1.6)}
    # the worst errors are rounding spikes, which a grid samples poorly: a
    # random sample of the same region, and the spikes tests/test_parity.py's
    # draws found
    rng = random.Random(0)                      # stdlib: the stream is stable
    for _ in range(200):
        p = rng.uniform(1.05, 1.1)
        rho = (2 - p) / (p - 1)
        z1 = tt.ZA + tt.S1 * (1 + rho) ** 2
        phi = math.exp(rng.uniform(math.log(0.01), math.log(2.0)))
        y = (rng.uniform(0.6, 1.0) * z1 * phi * (2 - p) * (p - 1)) ** (1 / (2 - p))
        graded.add((p, y * math.exp(rng.uniform(-0.5, 0.5)), phi, y))
    graded |= {(1.05, 0.7322062443874073, 0.020028698807062692, 0.6674935636203755),
               (1.05, 14.948103612343962, 0.40139605555805025, 14.238663807946466),
               (1.07, 12.087159758573403, 0.46620545614301584, 11.639439755817165),
               (1.05, 0.8697386997688737, 0.02401901878639002, 0.7764388225849072),
               (1.05, 42.37604975000736, 0.020616521318877278, 41.93810466188303)}
    # and random points over the whole box
    while len(graded) < 650:
        p = rng.uniform(1.05, 1.95)
        mu, phi = (math.exp(rng.uniform(math.log(lo), math.log(hi)))
                   for lo, hi in ((0.05, 50.0), (0.02, 5.0)))
        y = mu * math.exp(rng.uniform(-4.0, 3.0))
        if y ** (2 - p) / (phi * (2 - p) * (p - 1)) <= 1e5:
            graded.add((p, mu, phi, y))
    density = []
    for c in cases + sorted(graded - set(cases)):
        row = dict(zip(("p", "mu", "phi", "y"), c), value=float(ref.tweedie_logpdf(*c)))
        if c in graded:
            row["grad"] = [float(ref.tweedie_grad(*c, i)) if not (i == 3 and c[3] == 0) else None
                           for i in range(4)]
        density.append(row)
    return {"log_wright_bessel0": wright, "tweedie_logpdf": density,
            "references": "mpmath at 40 dps, tools/references.py"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("families", nargs="*", default=sorted(FAMILIES))
    ap.add_argument("--fixtures", action="store_true")
    args = ap.parse_args()
    for fam in args.families:
        export_family(fam)
        if args.fixtures:
            out = ROOT / "tests" / "fixtures" / f"{fam}.json"
            out.write_text(json.dumps(globals()[f"{fam}_fixtures"](), indent=1) + "\n")
            print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
